'use strict';
// ---------------------------------------------------------------------------
// ui.js — "Dream Glass" UI primitives (docs/HUD.md). Layout lives in hud.js; this file only draws pieces
// and owns the hit-region + focus model shared by mouse, touch and gamepad. Loaded after font.js (FONT_ART,
// UI_ART) and before hud.js, in index.html AND editor.html. No dependency on G / IN at load time.
//
// THE 2x GRID RULE: every UI pixel is a 2x2 block on the 960x540 canvas. All UI.* calls snap x/y/w/h to even
// numbers (UI.snap) and draw 1x art at scale 2, so callers may pass any number and still land on the grid.
//
// API
//   UI.theme / UI.C            palette table (bg line bright bevel edge text dim gold hp hpHi mp mpHi st stHi xp
//                              danger weak resist) — from UI_ART.palette when present. UI.el(element) = element colour.
//   UI.snap(v)                 -> nearest even integer.     UI.S = 2 (art scale)
//   UI.SIZES                   { small: 14 px line, body: 18, heading: 27 } (glyph h 7/9 at x2, heading = body x3)
//
//   UI.text(ctx, s, x, y, size='body', col=C.text, align='left', o)   -> drawn width (px)
//        size: 'small' | 'body' | 'heading' | number (legacy px: <=10 small, <=18 body, else heading)
//        o: { shadow:true, outline:(heading), alpha }  — 2 px #0b0716 shadow at +2,+2; heading gets a 2 px outline.
//        Bitmap glyphs from FONT_ART (tinted per colour, cached); canvas-text fallback until the sheets decode.
//   UI.measure(s, size)        -> width in px.   UI.lineH(size) -> recommended line pitch in px.
//   UI.ring(ctx, x, y, r, frac, col, w=2)  clockwise arc from 12 o'clock over frac (0..1) of the circle.
//   UI.wrap(ctx, s, x, y, w, size, col, lh) -> y after the last line (word wrap; '\n' breaks).
//
//   UI.frame(ctx, x, y, w, h, kind='plain', o)
//        9-slice from the UI_ART atlas. kind: 'primary' (crescent ornament) | 'plain' | 'gold' | 'danger' |
//        'tab' (= tabActive) | 'tabActive' | 'tabInactive' | 'slot' | 'rarity' | 'element' | 'keyTag' | 'keyTagMp' |
//        'keycap' | 'focus' | any other UI_ART.frames name.
//        o: { rarity:'epic' }  -> slot + rim tinted by the rarity colour (+ colourblind corner shape when
//                                 SETTINGS.rarityShapes is on, or o.shape:true)
//           { el:'fire' } / { col:'#hex' } -> slot + rim tinted (element frame, or any colour)
//           { tint:'#hex' }    -> tint a white frame (focus, slotRim)      { alpha }
//   UI.sprite(ctx, name, x, y, o={scale:2,tint,alpha})  -> {w,h} drawn size; UI_ART.sprites or frames by name.
//   UI.pad(kind)               -> suggested content inset in px for a frame kind.
//
//   UI.bar(ctx, x, y, w, h, frac, o)
//        o: { id, col, hi, back, ghost:true, wipe:true, label, labelCol, labelSize:'small', edge:true }
//        Ghost: a white fill lags 0.4 s behind damage, then drains. Heals fill with a bright wipe (0.25 s).
//        State is keyed by o.id (default "x,y"). UI.barReset(id) forgets it.
//   UI.sweep(ctx, x, y, w, h, frac, o)  radial cooldown: frac = remaining (1 = all dark), clockwise from 12 o'clock,
//        o: { alpha:0.7, col:C.edge, label, labelSize:'small' }. Rendered on the 2x grid (chunky edge).
//
//   UI.toast(msg | { text, icon:canvas, rarity, col, hold:3 })  queue a toast (max 6 live).
//   UI.drawToasts(ctx, o={ x:944, y:392 })   right-aligned, stacking upward; slide-in 150 ms, hold 3 s, fade.
//   UI.tooltip(ctx, x, y, content, o={ w:280, size:'small' }) -> rect. content: string | { title, titleCol,
//        lines:[ string | { s, col, size } | '' (gap) ] }. Flips to stay on screen.
//   UI.button(ctx, x, y, w, h, label, o) -> { hover, focus }. o: { id, fn(alt), alt, kind:'plain', on, disabled,
//        icon:canvas, size:'body', col }. Registers a hit region AND a focus target.
//
//   Hit regions (mouse/touch):  UI.begin() once per frame before drawing (main.js does it);
//        UI.hit(x, y, w, h, fn, o) registers; UI.click(x, y, alt) dispatches -> true if something was hit.
//   UI.focus — the menu focus model (CONTROLS.md):
//        register(rect, id, o={fn, alt, def}) -> true if focused. Screens register every focusable rect each frame.
//        move('up'|'down'|'left'|'right') nearest rect in that direction (never hand-wired), accept(), alt(),
//        set(id, show), is(id), current() -> rect, showing() -> ring visible, since() -> seconds focused,
//        tooltipReady(ms=150), draw(ctx) the 2 px bright focus ring. The ring shows after directional nav or on a pad.
//
// FONT_ART / UI_ART contract (js/font.js, generated by tools/ui/build-ui.js):
//   FONT_ART.small|body = { h, lineH, base, spaceAdv, glyphs:{ ch:{x,y,w,adv} }, src }, FONT_ART.fold = { ch: ch }
//   UI_ART = { palette, src, frames:{ name:{x,y,w,h,slice:[l,t,r,b],pad} }, sprites:{ name:{x,y,w,h} } }
// ---------------------------------------------------------------------------
const UI = (() => {
  const S = 2;
  const snap = v => Math.round(v / 2) * 2;
  const now = () => (typeof G !== 'undefined' && G && typeof G.t === 'number') ? G.t : performance.now() / 1000;
  const ART = () => (typeof UI_ART !== 'undefined' ? UI_ART : window.UI_ART);
  const FA = () => (typeof FONT_ART !== 'undefined' ? FONT_ART : window.FONT_ART);

  // ---- palette -------------------------------------------------------------------------------------------
  const C = Object.assign({
    bg: '#15102a', line: '#8f7bd6', bright: '#c8b6ff', bevel: '#4a3d7a', edge: '#0b0716', text: '#f3ecff', dim: '#9f93c4',
    gold: '#ffd35a', hp: '#e8476c', hpHi: '#ff8fa8', mp: '#4f7df0', mpHi: '#9ab8ff', st: '#e3a93a', stHi: '#ffe08a',
    xp: '#b48aff', danger: '#ff3d6e',
  }, (ART() && ART().palette) || {}, { weak: '#ffe36a', resist: '#a7a3b8', back: '#241a3e', ghost: '#f3ecff' });
  const RARITY_SHAPE = { common: '◇', uncommon: '○', rare: '△', epic: '☆', legendary: '✦', mythic: '✦✦' };
  function elCol(el) {
    try { if (typeof ICONS !== 'undefined' && ICONS.elementColor) { const c = ICONS.elementColor(el); if (c) return c; } } catch (e) { /* fall through */ }
    return (typeof EL_COL !== 'undefined' && EL_COL[el]) || C.line;
  }
  function rarCol(r) {
    if (typeof rarityCol === 'function') try { return rarityCol(r); } catch (e) { /* fall through */ }
    return (typeof RARITY !== 'undefined' && RARITY[r] && RARITY[r].col) || C.line;
  }

  // ---- images: decode the data URIs once, tint white art per colour (cached) --------------------------
  const imgs = {};
  function image(src) {
    if (!src) return null;
    let im = imgs[src];
    if (!im) { im = imgs[src] = new Image(); im.src = src; }
    return im.complete && im.naturalWidth ? im : null;
  }
  const tintCache = new Map();
  function tinted(img, col, key) {
    const k = key + '|' + col;
    let c = tintCache.get(k);
    if (!c) {
      if (tintCache.size > 160) tintCache.clear();
      c = document.createElement('canvas'); c.width = img.width; c.height = img.height;
      const x = c.getContext('2d'); x.drawImage(img, 0, 0);
      x.globalCompositeOperation = 'source-in'; x.fillStyle = col; x.fillRect(0, 0, c.width, c.height);
      tintCache.set(k, c);
    }
    return c;
  }

  // ---- text ------------------------------------------------------------------------------------------------
  const SIZES = { small: { face: 'small', sc: 2 }, body: { face: 'body', sc: 2 }, heading: { face: 'body', sc: 3 } };
  const sizeOf = size => typeof size === 'number' ? (size <= 10 ? SIZES.small : size <= 18 ? SIZES.body : SIZES.heading) : (SIZES[size] || SIZES.body);
  const FALLBACK_PX = { small: 7, body: 9 };
  function face(name) {
    const fa = FA(); const f = fa && fa[name];
    if (!f || !f.glyphs) return null;
    const img = image(f.src);
    return img ? { f, img, fold: fa.fold || {} } : null;
  }
  const glyphOf = (F, ch) => F.f.glyphs[ch] || F.f.glyphs[F.fold[ch]] || (ch === ' ' ? null : F.f.glyphs[ch.toUpperCase()] || F.f.glyphs['?']);
  let mctx = null;
  function fallbackFont(sz) { return `${FALLBACK_PX[sz.face] * sz.sc}px "Press Start 2P", "Courier New", monospace`; }
  function measure(s, size = 'body') {
    s = String(s); const sz = sizeOf(size), F = face(sz.face);
    if (F) {
      let w = 0;
      for (const ch of s) { const g = glyphOf(F, ch); w += g ? g.adv : (F.f.spaceAdv || 3); }
      return Math.max(0, w - 1) * sz.sc;
    }
    if (!mctx) mctx = document.createElement('canvas').getContext('2d');
    mctx.font = fallbackFont(sz);
    return Math.ceil(mctx.measureText(s).width);
  }
  const lineH = size => { const sz = sizeOf(size), fa = FA(), f = fa && fa[sz.face]; return (f ? f.lineH : sz.face === 'small' ? 9 : 11) * sz.sc; };
  function drawRun(ctx, F, s, x, y, sc, col) {
    const t = tinted(F.img, col, F.f.name || F.f.src.slice(-24));
    for (const ch of s) {
      const g = glyphOf(F, ch);
      if (!g) { x += (F.f.spaceAdv || 3) * sc; continue; }
      if (g.w) ctx.drawImage(t, g.x, g.y, g.w, F.f.h, x, y, g.w * sc, F.f.h * sc);
      x += g.adv * sc;
    }
  }
  // ---- text-run cache (DESIGN §26.4 step 5): a HUD frame drew ~300 glyph blits, each label 1-10 times (outline, shadow, fill).
  // A run seen twice is rastered once - outline, shadow and fill, in the same order, into a canvas at the target's device scale
  // - and blitted. Only under a plain whole-pixel transform at alpha 1 / source-over, so the pixels are the ones the direct
  // draw makes; otherwise (fading text, a scaled menu, the fallback font) the direct path runs as before. TEXT_MAX entries;
  // strings seen once (fresh damage numbers) never allocate.
  const TEXT_CACHE = new Map(), TEXT_SEEN = new Map(), TEXT_MAX = 400, TEXT_PAD = 2;
  function textCached(ctx, F, s, x, y, sz, col, outline, shadow, w) {
    if (ctx.globalAlpha !== 1 || ctx.globalCompositeOperation !== 'source-over') return false;
    const T = ctx.getTransform(), K = T.a;
    if (T.b !== 0 || T.c !== 0 || T.d !== K || K !== Math.round(K) || K < 1 || T.e !== Math.round(T.e) || T.f !== Math.round(T.f)) return false;
    const k = s + '\u0001' + sz.face + '|' + sz.sc + '|' + col + '|' + (outline ? 1 : 0) + (shadow ? 1 : 0) + '|' + K;
    let c = TEXT_CACHE.get(k);
    if (!c) {
      const n = (TEXT_SEEN.get(k) || 0) + 1;
      if (n < 2) { if (TEXT_SEEN.size > TEXT_MAX * 4) TEXT_SEEN.clear(); TEXT_SEEN.set(k, n); return false; }
      TEXT_SEEN.delete(k);
      if (TEXT_CACHE.size >= TEXT_MAX) TEXT_CACHE.clear();
      const P = TEXT_PAD, cw = Math.max(1, w + 2 * P + 4 * sz.sc), ch = F.f.h * sz.sc + 2 * P + 2 * sz.sc;
      c = document.createElement('canvas'); c.width = cw * K; c.height = ch * K;
      const x2 = c.getContext('2d'); x2.setTransform(K, 0, 0, K, 0, 0); x2.imageSmoothingEnabled = false;
      if (outline) for (const [dx, dy] of OUTLINE) drawRun(x2, F, s, P + dx, P + dy, sz.sc, C.edge);
      if (shadow) drawRun(x2, F, s, P + 2, P + 2, sz.sc, C.edge);
      drawRun(x2, F, s, P, P, sz.sc, col);
      c.cw = cw; c.ch = ch; TEXT_CACHE.set(k, c);
    }
    const sm = ctx.imageSmoothingEnabled; ctx.imageSmoothingEnabled = false;
    ctx.drawImage(c, x - TEXT_PAD, y - TEXT_PAD, c.cw, c.ch);
    ctx.imageSmoothingEnabled = sm;
    return true;
  }
  const OUTLINE = [[-2, 0], [2, 0], [0, -2], [0, 2], [-2, -2], [2, -2], [-2, 2], [2, 2]];
  function text(ctx, s, x, y, size = 'body', col = C.text, align = 'left', o = {}) {
    s = s == null ? '' : String(s); if (!s) return 0;
    const sz = sizeOf(size), w = measure(s, size);
    if (align === 'center') x -= w / 2; else if (align === 'right') x -= w;
    x = snap(x); y = snap(y);
    const outline = o.outline != null ? o.outline : size === 'heading', shadow = o.shadow !== false;
    const a0 = ctx.globalAlpha; if (o.alpha != null) ctx.globalAlpha = a0 * o.alpha;
    const F = face(sz.face);
    if (F && textCached(ctx, F, s, x, y, sz, col, outline, shadow, w)) { /* one blit of the cached run */ }
    else if (F) {
      if (outline) for (const [dx, dy] of OUTLINE) drawRun(ctx, F, s, x + dx, y + dy, sz.sc, C.edge);
      if (shadow) drawRun(ctx, F, s, x + 2, y + 2, sz.sc, C.edge);
      drawRun(ctx, F, s, x, y, sz.sc, col);
    } else {   // fallback until the sheets decode (or a page without font.js)
      ctx.font = fallbackFont(sz); ctx.textAlign = 'left'; ctx.textBaseline = 'top';
      if (outline) { ctx.fillStyle = C.edge; for (const [dx, dy] of OUTLINE) ctx.fillText(s, x + dx, y + dy); }
      if (shadow) { ctx.fillStyle = C.edge; ctx.fillText(s, x + 2, y + 2); }
      ctx.fillStyle = col; ctx.fillText(s, x, y);
    }
    ctx.globalAlpha = a0;
    return w;
  }
  function wrap(ctx, s, x, y, w, size = 'body', col = C.text, lh) {
    lh = lh || lineH(size);
    for (const para of String(s).split('\n')) {
      let line = '';
      for (const wd of para.split(' ')) {
        const t = line ? line + ' ' + wd : wd;
        if (measure(t, size) > w && line) { text(ctx, line, x, y, size, col); y += lh; line = wd; } else line = t;
      }
      if (line) text(ctx, line, x, y, size, col);
      y += lh;
    }
    return y;
  }

  // ---- 9-slice frames ----------------------------------------------------------------------------------
  const KIND_ALIAS = { tab: 'tabActive' };
  function slice9(ctx, img, fr, x, y, w, h) {   // x,y,w,h in display px; source corners drawn at S
    const [l, t, r, b] = fr.slice || [4, 4, 4, 4];
    const sw = Math.max(l + r, Math.round(w / S)), sh = Math.max(t + b, Math.round(h / S));
    const cw = fr.w - l - r, ch = fr.h - t - b, mw = sw - l - r, mh = sh - t - b;
    const D = (sx, sy, sW, sH, dx, dy, dW, dH) => { if (sW > 0 && sH > 0 && dW > 0 && dH > 0) ctx.drawImage(img, fr.x + sx, fr.y + sy, sW, sH, x + dx * S, y + dy * S, dW * S, dH * S); };
    D(0, 0, l, t, 0, 0, l, t); D(fr.w - r, 0, r, t, sw - r, 0, r, t); D(0, fr.h - b, l, b, 0, sh - b, l, b); D(fr.w - r, fr.h - b, r, b, sw - r, sh - b, r, b);
    D(l, 0, cw, t, l, 0, mw, t); D(l, fr.h - b, cw, b, l, sh - b, mw, b); D(0, t, l, ch, 0, t, l, mh); D(fr.w - r, t, r, ch, sw - r, t, r, mh);
    D(l, t, cw, ch, l, t, mw, mh);
  }
  const frameCache = new Map();
  function tintedFrame(img, fr, name, w, h, col) {   // white frames (focus, slotRim) are tinted after slicing
    const k = `${name}|${w}x${h}|${col}`;
    let c = frameCache.get(k);
    if (!c) {
      if (frameCache.size > 200) frameCache.clear();
      c = document.createElement('canvas'); c.width = w; c.height = h;
      const x = c.getContext('2d'); x.imageSmoothingEnabled = false;
      slice9(x, img, fr, 0, 0, w, h);
      x.globalCompositeOperation = 'source-in'; x.fillStyle = col; x.fillRect(0, 0, w, h);
      frameCache.set(k, c);
    }
    return c;
  }
  // procedural fallback (no atlas yet): fill + 2 px edge + 2 px line, per HUD.md
  function plainFallback(ctx, x, y, w, h, line) {
    ctx.fillStyle = C.edge; ctx.fillRect(x, y, w, h);
    ctx.fillStyle = line; ctx.fillRect(x + 2, y + 2, w - 4, h - 4);
    ctx.fillStyle = 'rgba(21,16,42,0.92)'; ctx.fillRect(x + 4, y + 4, w - 8, h - 8);
  }
  function frame(ctx, x, y, w, h, kind = 'plain', o = {}) {
    x = snap(x); y = snap(y); w = snap(w); h = snap(h);
    if (w <= 0 || h <= 0) return;
    const A = ART(), img = A && image(A.src), a0 = ctx.globalAlpha;
    if (o.alpha != null) ctx.globalAlpha = a0 * o.alpha;
    const sm = ctx.imageSmoothingEnabled; ctx.imageSmoothingEnabled = false;
    let rim = null;
    if (kind === 'rarity') rim = rarCol(o.rarity);
    else if (kind === 'element') rim = elCol(o.el);
    else if (o.col && (kind === 'slot' || kind === 'rim')) rim = o.col;
    const name = rim ? 'slot' : (KIND_ALIAS[kind] || kind);
    const fr = A && A.frames && A.frames[name];
    if (img && fr) {
      if (o.tint) ctx.drawImage(tintedFrame(img, fr, name, w, h, o.tint), x, y);
      else slice9(ctx, img, fr, x, y, w, h);
      if (rim && A.frames.slotRim) ctx.drawImage(tintedFrame(img, A.frames.slotRim, 'slotRim', w, h, rim), x, y);
    } else plainFallback(ctx, x, y, w, h, rim || o.tint || (kind === 'gold' ? C.gold : kind === 'danger' ? C.danger : C.line));
    if (kind === 'rarity' && (o.shape || rarityShapesOn())) text(ctx, RARITY_SHAPE[o.rarity] || '', x + 4, y + 2, 'small', rim, 'left', { shadow: true });
    ctx.imageSmoothingEnabled = sm; ctx.globalAlpha = a0;
  }
  const rarityShapesOn = () => typeof SETTINGS !== 'undefined' && !!SETTINGS.rarityShapes;
  function pad(kind) { const A = ART(), fr = A && A.frames && A.frames[KIND_ALIAS[kind] || kind]; return ((fr && fr.pad) || 4) * S; }
  function sprite(ctx, name, x, y, o = {}) {
    const A = ART(), img = A && image(A.src), s = A && ((A.sprites && A.sprites[name]) || (A.frames && A.frames[name]));
    const sc = o.scale || S;
    if (!s) return { w: 0, h: 0 };
    if (img) {
      const a0 = ctx.globalAlpha; if (o.alpha != null) ctx.globalAlpha = a0 * o.alpha;
      const sm = ctx.imageSmoothingEnabled; ctx.imageSmoothingEnabled = false;
      ctx.drawImage(o.tint ? tinted(img, o.tint, 'atlas') : img, s.x, s.y, s.w, s.h, snap(x), snap(y), s.w * sc, s.h * sc);
      ctx.imageSmoothingEnabled = sm; ctx.globalAlpha = a0;
    }
    return { w: s.w * sc, h: s.h * sc };
  }

  // ---- bars: ghost lag on damage, bright wipe on heal ----------------------------------------------------------
  const bars = {};
  function bar(ctx, x, y, w, h, frac, o = {}) {
    x = snap(x); y = snap(y); w = snap(w); h = snap(h);
    frac = clamp(+frac || 0, 0, 1);
    const id = o.id || `${x},${y}`, t = now();
    let st = bars[id];
    if (!st) st = bars[id] = { v: frac, ghost: frac, hold: 0, wFrom: frac, wT: -1, last: t };
    const dt = clamp(t - st.last, 0, 0.1); st.last = t;
    if (frac < st.v - 1e-4) { st.ghost = Math.max(st.ghost, st.v); st.hold = t + 0.4; st.wT = -1; }
    else if (frac > st.v + 1e-4) { if (st.wT < 0 || t - st.wT > 0.25) st.wFrom = st.v; st.wT = t; st.ghost = Math.min(st.ghost, frac); }
    st.v = frac;
    if (t > st.hold) st.ghost = Math.max(frac, st.ghost - dt * 1.2);
    let shown = frac, wipeK = -1;
    if (o.wipe !== false && st.wT >= 0) {
      const k = (t - st.wT) / 0.25;
      if (k >= 1) st.wT = -1; else { wipeK = k; shown = st.wFrom + (frac - st.wFrom) * (1 - (1 - k) * (1 - k)); }
    }
    const col = o.col || C.hp, hi = o.hi || C.hpHi;
    if (o.edge !== false) { ctx.fillStyle = C.edge; ctx.fillRect(x - 2, y - 2, w + 4, h + 4); }
    ctx.fillStyle = o.back || C.back; ctx.fillRect(x, y, w, h);
    const W = v => snap(w * v);
    if (o.ghost !== false && st.ghost > shown) { ctx.fillStyle = C.ghost; ctx.globalAlpha *= 0.85; ctx.fillRect(x, y, W(st.ghost), h); ctx.globalAlpha /= 0.85; }
    const fw = W(shown);
    ctx.fillStyle = col; ctx.fillRect(x, y, fw, h);
    if (h >= 6) { ctx.fillStyle = hi; ctx.fillRect(x, y, fw, 2); }
    if (wipeK >= 0 && fw > 0) { const lead = Math.min(fw, 8); ctx.fillStyle = hi; ctx.fillRect(x + fw - lead, y, lead, h); ctx.fillStyle = '#ffffff'; ctx.fillRect(x + fw - 2, y, 2, h); }
    if (o.label != null && o.label !== '') {
      const ls = o.labelSize || 'small', ly = y + Math.round((h - lineH(ls) + 2) / 2);
      text(ctx, o.label, o.labelAlign === 'center' ? x + w / 2 : o.labelAlign === 'left' ? x + 4 : x + w - 4, ly, ls, o.labelCol || C.text, o.labelAlign || 'right');
    }
    return st;
  }
  const barReset = id => { delete bars[id]; };

  // ---- radial cooldown sweep ---------------------------------------------------------------------------
  const sweepC = {};
  function sweep(ctx, x, y, w, h, frac, o = {}) {
    x = snap(x); y = snap(y); w = snap(w); h = snap(h);
    frac = clamp(+frac || 0, 0, 1);
    if (frac > 0) {
      const lw = w / 2, lh = h / 2, k = lw + 'x' + lh;
      let c = sweepC[k]; if (!c) { c = sweepC[k] = document.createElement('canvas'); c.width = lw; c.height = lh; }
      const sx = c.getContext('2d'); sx.clearRect(0, 0, lw, lh);
      const cx = lw / 2, cy = lh / 2, R = Math.hypot(lw, lh), a0 = -Math.PI / 2 + (1 - frac) * Math.PI * 2;
      sx.fillStyle = o.col || C.edge; sx.beginPath(); sx.moveTo(cx, cy); sx.arc(cx, cy, R, a0, Math.PI * 1.5); sx.closePath(); sx.fill();
      const ga = ctx.globalAlpha, sm = ctx.imageSmoothingEnabled;
      ctx.globalAlpha = ga * (o.alpha != null ? o.alpha : 0.7); ctx.imageSmoothingEnabled = false;
      ctx.drawImage(c, x, y, w, h);
      ctx.globalAlpha = ga; ctx.imageSmoothingEnabled = sm;
    }
    if (o.label != null && o.label !== '') { const ls = o.labelSize || 'small'; text(ctx, o.label, x + w / 2, y + (h - lineH(ls)) / 2 + 2, ls, C.text, 'center'); }
  }

  // ---- toasts --------------------------------------------------------------------------------------------
  const toasts = [];
  function toast(m) {
    const o = typeof m === 'string' ? { text: m } : Object.assign({}, m);
    o.t0 = now(); o.hold = o.hold || 3;
    // loot toasts: icons.js art (24 px, frame baked in) for an item. Callers may pass { item }; items.js pickup() still passes the
    // 16 px itemIcon, so a rarity toast finds the just-picked item in the bag by name instead (see uiToastItem)
    if (!o.item && o.rarity && typeof uiToastItem === 'function') o.item = uiToastItem(o);
    if (o.item && typeof uiItemIcon === 'function' && typeof ICONS !== 'undefined') { o.icon = uiItemIcon(o.item); o.framed = true; }
    toasts.push(o); while (toasts.length > 6) toasts.shift();
    return o;
  }
  function drawToasts(ctx, o = {}) {
    const X = o.x != null ? o.x : 944, t = now();
    let y = o.y != null ? o.y : 392;
    for (let i = toasts.length - 1; i >= 0; i--) {
      const q = toasts[i], age = t - q.t0;
      if (age < 0) q.t0 = t;   // clock went backwards (new game): restart
      if (age > q.hold + 0.3) { toasts.splice(i, 1); continue; }
      const col = q.col || (q.rarity ? rarCol(q.rarity) : C.text), tw = measure(q.text, 'body'), iw = q.icon ? 32 : 0;
      const w = tw + iw + 20, h = 32, slide = age < 0.15 ? (1 - age / 0.15) * (w + 16) : 0;
      const a = age > q.hold ? 1 - (age - q.hold) / 0.3 : 1, x = X - w + slide;
      const ga = ctx.globalAlpha; ctx.globalAlpha = ga * clamp(a, 0, 1);
      frame(ctx, x, y - h, w, h, 'plain');
      if (q.icon && q.framed) ctx.drawImage(q.icon, snap(x + 4), snap(y - h + 4), 24, 24);   // ICONS.item art carries its own rarity frame
      else if (q.icon) { frame(ctx, x + 4, y - h + 2, 28, 28, q.rarity ? 'rarity' : 'slot', { rarity: q.rarity }); ctx.drawImage(q.icon, snap(x + 6), snap(y - h + 4), 24, 24); }
      text(ctx, q.text, x + 10 + iw, y - h + 8, 'body', col);
      ctx.globalAlpha = ga;
      y -= h + 4;
    }
  }

  // ---- tooltip -----------------------------------------------------------------------------------------------
  function tooltip(ctx, x, y, content, o = {}) {
    const c = typeof content === 'string' ? { lines: [content] } : content || {};
    const w = snap(o.w || 280), P = 12, size = o.size || 'small', inner = w - P * 2;
    const L = [];
    if (c.title) L.push({ s: c.title, col: c.titleCol || C.gold, size: 'body' });
    for (const l of c.lines || []) L.push(typeof l === 'string' ? { s: l, col: C.text, size } : Object.assign({ col: C.text, size }, l));
    // measure height by wrapping into a throwaway pass
    let hgt = P;
    const lines = [];
    for (const l of L) {
      if (!l.s) { hgt += 6; lines.push(null); continue; }
      const lh = lineH(l.size), rows = []; let line = '';
      for (const wd of String(l.s).split(' ')) { const t = line ? line + ' ' + wd : wd; if (measure(t, l.size) > inner && line) { rows.push(line); line = wd; } else line = t; }
      if (line) rows.push(line);
      lines.push({ rows, l, lh }); hgt += rows.length * lh;
    }
    const h = snap(hgt + P - 4);
    if (x + w > DW - 8) x = (o.anchorW ? x - w - o.anchorW : DW - 8 - w);
    if (y + h > DH - 8) y = DH - 8 - h;
    x = snap(Math.max(8, x)); y = snap(Math.max(8, y));
    frame(ctx, x, y, w, h, o.kind || 'plain');
    let yy = y + P;
    for (const q of lines) { if (!q) { yy += 6; continue; } for (const r of q.rows) { text(ctx, r, x + P, yy, q.l.size, q.l.col); yy += q.lh; } }
    return { x, y, w, h };
  }

  // ---- hit regions (mouse / touch) --------------------------------------------------------------------------
  let hits = [];
  function hit(x, y, w, h, fn, o = {}) { const r = { x, y, w, h, fn, alt: o.alt, id: o.id }; hits.push(r); return r; }
  function click(x, y, alt) {
    for (let i = hits.length - 1; i >= 0; i--) { const r = hits[i]; if (x >= r.x && x < r.x + r.w && y >= r.y && y < r.y + r.h) { if (alt && r.alt) r.alt(); else if (r.fn) r.fn(alt); return true; } }
    return false;
  }
  const mouseIn = (x, y, w, h) => {
    if (typeof G === 'undefined' || !G.mouse) return false;
    if (typeof IN !== 'undefined' && IN.device !== 'kbm' && IN.device !== 'touch') return false;
    const m = G.mouse; return m.dx >= x && m.dx < x + w && m.dy >= y && m.dy < y + h;
  };

  // ---- focus model ---------------------------------------------------------------------------------------------
  const focus = {
    list: [], id: null, rect: null, t0: 0, nav: false,
    begin() { this.list = []; },
    register(rect, id, o = {}) {
      const r = { x: rect.x, y: rect.y, w: rect.w, h: rect.h, id: id != null ? id : `${rect.x},${rect.y}`, fn: o.fn, alt: o.alt, def: !!o.def };
      this.list.push(r);
      if (r.id === this.id) this.rect = r;
      return r.id === this.id;
    },
    _valid() {
      const L = this.list; if (!L.length) return null;
      const cur = L.find(r => r.id === this.id);
      if (cur) return (this.rect = cur);
      // focused target vanished: nearest to where it was, else the default, else the first
      let best = L.find(r => r.def) || L[0];
      if (this.rect && !L.find(r => r.def)) { let bd = 1e9; for (const r of L) { const d = Math.hypot(r.x - this.rect.x, r.y - this.rect.y); if (d < bd) { bd = d; best = r; } } }
      this.set(best.id); return (this.rect = best);
    },
    set(id, show) { if (id !== this.id) { this.id = id; this.t0 = now(); } if (show != null) this.nav = !!show; const r = this.list.find(q => q.id === id); if (r) this.rect = r; },
    is(id) { return this.id === id; },
    current() { return this._valid(); },
    move(dir) {
      const cur = this._valid(); if (!cur) return null;
      const D = { up: [0, -1], down: [0, 1], left: [-1, 0], right: [1, 0] }[dir] || dir;
      const cx = cur.x + cur.w / 2, cy = cur.y + cur.h / 2;
      let best = null, bs = 1e9;
      for (const r of this.list) {
        if (r === cur) continue;
        const rx = r.x + r.w / 2, ry = r.y + r.h / 2, dx = rx - cx, dy = ry - cy;
        const along = dx * D[0] + dy * D[1]; if (along <= 2) continue;
        // perpendicular distance; zero when the rects overlap on the cross axis (same row / column)
        const overlap = D[0] ? (r.y < cur.y + cur.h && r.y + r.h > cur.y) : (r.x < cur.x + cur.w && r.x + r.w > cur.x);
        const perp = overlap ? 0 : Math.abs(dx * D[1] + dy * D[0]);
        const s = along + perp * 2.5;
        if (s < bs) { bs = s; best = r; }
      }
      this.nav = true;
      if (best) this.set(best.id);
      return best;
    },
    accept() { const r = this._valid(); if (r && r.fn) { r.fn(false); return true; } return false; },
    alt() { const r = this._valid(); if (r && (r.alt || r.fn)) { if (r.alt) r.alt(); else r.fn(true); return true; } return false; },
    showing() { return this.nav || (typeof IN !== 'undefined' && IN.device === 'pad'); },
    since() { return now() - this.t0; },
    tooltipReady(ms = 150) { return this.showing() && this.since() * 1000 >= ms; },
    draw(ctx) {
      if (!this.showing()) return;
      const r = this._valid(); if (!r) return;
      const x = snap(r.x - 4), y = snap(r.y - 4), w = snap(r.w + 8), h = snap(r.h + 8);
      const A = ART();
      if (A && A.frames && A.frames.focus && image(A.src)) frame(ctx, x, y, w, h, 'focus', { tint: C.bright });
      else { ctx.fillStyle = C.bright; ctx.fillRect(x, y, w, 2); ctx.fillRect(x, y + h - 2, w, 2); ctx.fillRect(x, y, 2, h); ctx.fillRect(x + w - 2, y, 2, h); }
    },
  };

  // ---- button --------------------------------------------------------------------------------------------------
  function button(ctx, x, y, w, h, label, o = {}) {
    const id = o.id || `btn:${x},${y}`;
    if (!o.disabled) { hit(x, y, w, h, o.fn, { alt: o.alt, id }); focus.register({ x, y, w, h }, id, { fn: o.fn, alt: o.alt, def: o.def }); }
    const hover = !o.disabled && mouseIn(x, y, w, h), foc = focus.is(id) && focus.showing();
    if (hover && !focus.nav) focus.set(id);
    const a0 = ctx.globalAlpha; if (o.disabled) ctx.globalAlpha = a0 * 0.5;
    frame(ctx, x, y, w, h, o.kind || (o.on ? 'tabActive' : 'plain'));
    let tx = x + w / 2;
    if (o.icon) { const s = Math.min(h - 8, 32); ctx.drawImage(o.icon, snap(x + 6), snap(y + (h - s) / 2), s, s); tx += (s + 4) / 2; }
    if (label) { const size = o.size || 'body'; text(ctx, label, tx, y + (h - lineH(size)) / 2 + 2, size, o.col || (o.on || hover || foc ? C.gold : C.text), 'center'); }
    ctx.globalAlpha = a0;
    return { hover, focus: foc };
  }

  function begin() { hits = []; focus.begin(); }

  // ring(ctx,x,y,r,frac,col[,w=2]): a clockwise arc from 12 o'clock covering frac of the circle (touch wheel rims,
  // cooldown / charge rings; docs/HUD.md "Touch v2"). Not grid-snapped: rings are round.
  function ring(ctx, x, y, r, frac, col, w = 2) {
    frac = Math.max(0, Math.min(1, frac)); if (frac <= 0) return;
    ctx.save(); ctx.strokeStyle = col; ctx.lineWidth = w; ctx.lineCap = 'butt';
    ctx.beginPath(); ctx.arc(x, y, r, -Math.PI / 2, -Math.PI / 2 + frac * Math.PI * 2); ctx.stroke(); ctx.restore();
  }
  return {
    S, snap, C, theme: C, SIZES: { small: 14, body: 18, heading: 27 }, el: elCol, rarityCol: rarCol, RARITY_SHAPE, ring,
    text, measure, lineH, wrap, frame, sprite, pad, bar, barReset, sweep, toast, toasts, drawToasts, tooltip, button,
    hit, click, mouseIn, begin, focus, image,
    // legacy colour keys some older call sites expect (hud.js keeps its own palette as HC until the rebuild)
    gold: C.gold, line: C.line, dim: C.dim, bg: C.bg,
  };
})();

// ===== item art routing (M3 UI lane): the ONE place the UI asks icons.js (ICONS) for item / gem / skill art ==========
// ICONS.item(base, tier, rarity, gems, opts) takes the item's BASE id (never a variant or suit id) and bakes the rarity frame +
// gem dots into a 24 px canvas. icons.js may not be loaded yet (editor.html, art lane mid-wire): every helper falls back to the
// legacy 16 px icon routing in items.js, so callers can always drawImage the result.
const ELEMENT_OF_DMG = { fireDmg: 'fire', frostDmg: 'frost', natureDmg: 'nature', lightningDmg: 'lightning', arcaneDmg: 'arcane', holyDmg: 'holy' };
function uiItemIcon(it) {
  if (!it) return null;
  if (typeof ICONS !== 'undefined' && ICONS.item) {
    try {
      const b = typeof baseOf === 'function' ? baseOf(it.base) : null, el = it.implicit && ELEMENT_OF_DMG[it.implicit.id] || null;
      return ICONS.item(it.base, it.tier != null ? it.tier : (b && b.tier) || 0, it.rarity, it.sockets || [], { element: el, implicit: el, tempered: !!it.tempered });
    } catch (e) { /* fall back */ }
  }
  return itemIcon(it);
}
const uiArt = () => typeof ICONS !== 'undefined' && !!ICONS.item;   // true when the 24 px art (with its own frame) is available
function uiGemIcon(gemId) {
  const g = typeof gemParse === 'function' ? gemParse(gemId) : null; if (!g) return null;
  if (typeof ICONS !== 'undefined' && ICONS.gem) { try { return ICONS.gem(g.type, g.grade - 1); } catch (e) { /* fall back */ } }   // ICONS grades are 0..2
  return gemIcon(g.type, g.grade);
}
function uiSkillIcon(id) {
  if (typeof ICONS !== 'undefined' && ICONS.skill) { try { return ICONS.skill(id); } catch (e) { /* fall back */ } }
  return skillIcon(id);
}
// a rarity toast whose item is in the hero's bag (pickup adds it before toasting): newest match by display name
function uiToastItem(o) {
  const p = typeof G !== 'undefined' && G.player; if (!p || !p.bag || typeof itemName !== 'function') return null;
  for (let i = p.bag.length - 1; i >= 0; i--) { const e = p.bag[i]; if (e && !e.gem && e.rarity === o.rarity && itemName(e) === o.text) return e; }
  return null;
}
