#!/usr/bin/env node
// Rewrites js/art-raster.js from the native raster PNGs (painted outside the forge, palette-snapped).
// The sources are git-ignored and live in tools/out/art/ of the main checkout; the generated js/art-raster.js is what ships.
// Usage: node tools/raster-embed.js [source-dir]   (default: $RASTER_SRC, else tools/out/art in this checkout)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = process.argv[2] || process.env.RASTER_SRC || path.join(ROOT, 'tools', 'out', 'art');
const OUT = path.join(ROOT, 'js', 'art-raster.js');
// id -> native file and size; sizes are checked so a wrong export never ships
const PIECES = [
  ['wordmark', 'wordmark.native.png', 240, 52],
  ['pip', 'pip.native.png', 32, 44],
  ['elderstone', 'elder-stone.native.png', 43, 44],
  ['foxkit', 'fox-kit.native.png', 44, 42],
];

const rows = PIECES.map(([id, file, w, h]) => {
  const buf = fs.readFileSync(path.join(SRC, file));
  if (buf.toString('latin1', 1, 4) !== 'PNG') throw new Error(file + ': not a PNG');
  const pw = buf.readUInt32BE(16), ph = buf.readUInt32BE(20);
  if (pw !== w || ph !== h) throw new Error(`${file}: ${pw}x${ph}, expected ${w}x${h}`);
  return `  ${id}: { w: ${w}, h: ${h}, src: 'data:image/png;base64,${buf.toString('base64')}' },`;
});

const src = `// Raster art embedded as data-URI PNGs (M4b): pieces painted outside the forge (codex-image), palette-snapped, at native size.
// GENERATED by tools/raster-embed.js from the git-ignored sources in tools/out/art/ (main checkout): do not edit by hand.
// Regenerate: node tools/raster-embed.js [source-dir]. See docs/design/visual-bible.md "Raster art (outside the forge)".
// API: RASTER.get(id) -> the decoded Image, or null while it decodes (or if it failed); RASTER.size(id) -> {w, h} | null.
// Ids: wordmark (title logo, 240x52), pip (32x44), elderstone (43x44), foxkit (44x42): the dialogue portraits.
const RASTER = (() => {
  const DATA = {
${rows.join('\n')}
  };
  const img = {};
  for (const id in DATA) {
    const im = new Image();
    im.onload = () => { img[id] = im; };
    im.src = DATA[id].src;
  }
  return {
    get(id) { return img[id] || null; },
    size(id) { return DATA[id] ? { w: DATA[id].w, h: DATA[id].h } : null; },
  };
})();
`;
fs.writeFileSync(OUT, src);
console.log(`wrote ${path.relative(ROOT, OUT)} (${(Buffer.byteLength(src) / 1024).toFixed(1)} KB)`);
