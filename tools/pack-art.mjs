// Packs pxl's rendered PNGs (art/out) into js/pxl-art.js as data URIs, so the game keeps
// working straight from file:// (no fetch, no tainted canvases).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const out = 'art/out', art = {};
for (const dir of ['sprites', 'anims']) {
  const d = join(out, dir);
  if (!existsSync(d)) continue;
  for (const f of readdirSync(d).filter(f => f.endsWith('.png')).sort()) {
    const name = f.slice(0, -4), json = join(d, name + '.json');
    const frames = existsSync(json) ? Object.keys(JSON.parse(readFileSync(json, 'utf8')).frames).length : 1;
    art[name] = { frames, src: 'data:image/png;base64,' + readFileSync(join(d, f)).toString('base64') };
  }
}
writeFileSync('js/pxl-art.js', "'use strict';\n// GENERATED by tools/pack-art.mjs from art/dreamy.px.js — do not edit by hand.\nconst PXL_ART = " + JSON.stringify(art, null, 0).replace(/\},"/g, '},\n"') + ';\n');
console.log(`packed ${Object.keys(art).length} assets into js/pxl-art.js`);
